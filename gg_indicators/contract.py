"""
The extended variable schema / data contract (JSON) for all 74 sheet rows, written to
docs/indicator_contract.json next to the existing docs/indicator_catalog.json. It does not replace
the catalog: each row names its `catalog_key` (the existing INDICATOR_SEED signal key, identical to
variable_key where one exists) and lists `catalog_differences`, the places where the sheet and the
live catalog disagree.
"""

from __future__ import annotations

from typing import Any, Dict, List

from .registry import IndicatorRegistry
from .schema import SCHEMA_VERSION, catalog_diff, own_group


def build_contract(reg: IndicatorRegistry, seed_rows: List[Dict[str, Any]]) -> Dict[str, Any]:
    seed_by_key = {d["key"]: d for d in seed_rows}
    variables = []
    for s in reg.specs:
        tier = reg.tier(s.key)
        diff = catalog_diff(s, seed_by_key, tier)
        m = reg.mapping(s.key)
        variables.append({
            "variable_key": s.key,
            "key_source": s.key_source,
            "sheet_row": s.sheet_row,
            "label": s.label,
            "origin": s.origin,
            "axis_tag_raw": s.tag.raw,
            "axis": s.tag.axis,
            "axes_scored": reg.axes_of(s.key) if reg.role(s.key) == "Scored" else [],
            "polarity": s.tag.polarity,
            "readiness_caveat": s.tag.readiness_caveat,
            "tag_modifiers": list(s.tag.modifiers),
            "role": reg.role(s.key),
            "acquisition_mode": s.acquisition_mode,
            "automation_tier": tier,
            "loaded_from": reg.acquisition_modes["modes"][s.acquisition_mode]["load_from"],
            "redundancy_group": reg.group_of(s.key) or own_group(s.key),
            "redundancy_group_in_sheet": s.redundancy_group_sheet,
            "weights_in_sheet": s.sheet_weights,
            "status_text": s.status_text,
            "status_mapping": {
                "polarity": m["polarity"], "trigger_labels": m["trigger_labels"], "axes": m["axes"],
                "direction": m["direction"], "states": m["states"], "labels_only": bool(m.get("labels_only")),
                "note": m.get("note"),
            },
            "gate": reg.roles_cfg["gates"].get(s.key),
            "applicability": [r for r in reg.applicability["ateco_rules"] if r["variable_key"] == s.key]
                              + [r for r in reg.applicability["attribute_rules"] if s.key in r["variable_keys"]],
            "asymmetric_absence_is_unknown": s.key in reg.interactions["asymmetric_variables"]["variables"],
            "source_text_sheet": s.source_text,
            "source_it": reg.source_it[s.key],
            "proxy": s.proxy,
            "indicator_text": s.indicator_text,
            "comment": s.comment,
            "catalog_key": s.key if diff["in_catalog_seed"] else None,
            **{k: v for k, v in diff.items()},
        })
    return {
        "$comment": "Generated by scripts/build_indicator_contract.py from gg_indicators/source/Indicators.xlsx + gg_indicators/settings/*.json - do not hand-edit.",
        "schema_version": SCHEMA_VERSION,
        "variable_count": len(variables),
        "sheet_weights_note": "The sheet's two weight columns are deliberately empty; weights live in versioned weight sets (gg_indicators/settings/weight_sets/).",
        "axis_rule": "contains CONTEXT -> CONTEXT; else contains BOTH -> BOTH; else contains uppercase READINESS -> READINESS; else NEED (case sensitive on purpose)",
        "redundancy_grouping": {"id": reg.grouping_id, "hash": reg.grouping_hash},
        "weight_sets_dir": "gg_indicators/settings/weight_sets",
        "variables": variables,
    }
